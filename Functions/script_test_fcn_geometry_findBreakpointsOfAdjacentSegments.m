endPointsMatrix = zeros(numel(sortedHoughSegmentEndPoints)/2, 2);

endPointsMatrix(1:2:end,:) = sortedHoughSegmentEndPoints(:,1:2);
endPointsMatrix(2:2:end,:) = sortedHoughSegmentEndPoints(:,3:4);

% [closeEndPointsMatrix, dist_btw_close_endPoints] = fcn_geometry_findEndPoints(endPointsMatrix(1,:), endPointsMatrix(2:end-1,:), endPointsMatrix(end,:), tolerance, -1);

curveStartPoint = sortedHoughSegmentEndPoints(1,1:2);
curveEndPoint = sortedHoughSegmentEndPoints(end,3:4);

intersectionPoints = fcn_geometry_findBreakpointsOfAdjacentSegments(curveStartPoint, sortedHoughSegmentEndPoints, curveEndPoint, figNum);

assert(isequal(round(intersectionPoints,4),[4.2773, 2.0001]));

